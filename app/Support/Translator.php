    public static function render(string $html): string
    {
        $protected = [];
        $html = preg_replace_callback('~<(script|style)\b[^>]*>.*?</\1>~is', static function (array $match) use (&$protected): string {
            $key = '__MOBILEX_PROTECTED_' . count($protected) . '__';
            $protected[$key] = $match[0];
            return $key;
        }, $html) ?? $html;

        $translations = self::translations();
        $html = preg_replace_callback('/>([^<>]+)</u', static function (array $match) use ($translations): string {
            $text = self::repairMojibake(html_entity_decode($match[1], ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            $trimmed = trim($text);
            $translated = $translations[$trimmed] ?? $trimmed;
            $leading = substr($text, 0, strlen($text) - strlen(ltrim($text)));
            $trailing = substr($text, strlen(rtrim($text)));
            return '>' . htmlspecialchars($leading . $translated . $trailing, ENT_NOQUOTES | ENT_SUBSTITUTE, 'UTF-8') . '<';
        }, $html) ?? $html;

        $html = preg_replace_callback('/\b(placeholder|aria-label|title|alt)="([^"]*)"/u', static function (array $match) use ($translations): string {
            $value = self::repairMojibake(html_entity_decode($match[2], ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            $translated = $translations[trim($value)] ?? $value;
            return $match[1] . '="' . htmlspecialchars($translated, ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8') . '"';
        }, $html) ?? $html;

        $html = str_replace('lang="en"', 'lang="vi"', $html);
        $html = preg_replace('~</body>~i', self::dynamicTranslationScript() . '</body>', $html, 1) ?? $html;
        return strtr($html, $protected);
    }

    private static function translations(): array
    {
        $translations = [];
        foreach (self::TEXT as $source => $target) {
            $source = self::repairMojibake(html_entity_decode($source, ENT_QUOTES | ENT_HTML5, 'UTF-8'));
            $translations[$source] = self::repairMojibake(html_entity_decode($target, ENT_QUOTES | ENT_HTML5, 'UTF-8'));
        }
        return $translations;
    }

    private static function repairMojibake(string $text): string
    {
        if (!preg_match('/(?:Ã|Â|Ä|áº|á»|Æ°|â€|â†)/u', $text)) {
            return $text;
        }
        $cp1252 = [
            '€' => 0x80, '‚' => 0x82, 'ƒ' => 0x83, '„' => 0x84, '…' => 0x85,
            '†' => 0x86, '‡' => 0x87, 'ˆ' => 0x88, '‰' => 0x89, 'Š' => 0x8A,
            '‹' => 0x8B, 'Œ' => 0x8C, 'Ž' => 0x8E, '‘' => 0x91, '’' => 0x92,
            '“' => 0x93, '”' => 0x94, '•' => 0x95, '–' => 0x96, '—' => 0x97,
            '˜' => 0x98, '™' => 0x99, 'š' => 0x9A, '›' => 0x9B, 'œ' => 0x9C,
            'ž' => 0x9E, 'Ÿ' => 0x9F,
        ];
        $bytes = '';
        foreach (preg_split('//u', $text, -1, PREG_SPLIT_NO_EMPTY) as $character) {
            $codepoint = mb_ord($character, 'UTF-8');
            $bytes .= isset($cp1252[$character]) ? chr($cp1252[$character]) : ($codepoint <= 0xFF ? chr($codepoint) : $character);
        }
        return @iconv('UTF-8', 'UTF-8', $bytes) ?: $text;
    }

    public static function repairSourceText(string $text): string
    {
        return self::repairMojibake($text);
    }

